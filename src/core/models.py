"""Core Pydantic data models for Your Tutor.

Enforces source provenance, page-level attribution, citation auditing structures,
and explicit model provider responses.
"""

from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, model_validator


class SourceType(str, Enum):
    """Supported source material formats."""
    PDF = "pdf"
    PPTX = "pptx"
    VIDEO_TRANSCRIPT = "video_transcript"
    SYNTHETIC_PDF = "synthetic_pdf"


class SourceDocument(BaseModel):
    """Represents an ingested course material document."""
    document_id: str = Field(description="Unique SHA256-derived ID of the source document")
    filename: str = Field(description="Original file name e.g., lecture_notes.pdf")
    source_type: SourceType = Field(default=SourceType.PDF, description="Format of the uploaded document")
    total_pages: Optional[int] = Field(default=None, description="Total physical pages in the document")
    file_size_bytes: int = Field(description="File size on disk in bytes")
    uploaded_at: str = Field(description="ISO 8601 UTC timestamp of ingestion")


class ContentChunk(BaseModel):
    """An atomic text chunk with strict physical page-level provenance."""
    chunk_id: str = Field(description="Deterministic hash of document_id + page + text")
    document_id: str = Field(description="Foreign key referencing SourceDocument.document_id")
    filename: str = Field(description="Filename for direct citation binding")
    source_type: SourceType = Field(default=SourceType.PDF, description="Source format")
    page_number: int = Field(ge=1, description="1-indexed physical page number")
    text_content: str = Field(description="Normalized textual content of the chunk")
    token_count: int = Field(default=0, description="Approximate word/token count")

    @model_validator(mode="after")
    def validate_content_and_page(self) -> "ContentChunk":
        if not self.text_content.strip():
            raise ValueError("ContentChunk text_content cannot be empty.")
        if self.page_number < 1:
            raise ValueError(f"Invalid page_number {self.page_number}; must be >= 1.")
        if self.token_count <= 0:
            self.token_count = len(self.text_content.split())
        return self


class EvidenceItem(BaseModel):
    """Retrieved chunk presented to the model provider and student as evidence."""
    chunk_id: str
    document_id: str
    filename: str
    page_number: int
    text_content: str
    score: float = Field(description="Retrieval relevance score")
    rank: int = Field(ge=1, description="1-indexed retrieval rank")

    @property
    def citation_label(self) -> str:
        """Standard formatted citation badge."""
        return f"[Source: {self.filename}, Page {self.page_number}]"


class AuditResult(BaseModel):
    """Outcome of the independent citation auditing layer."""
    is_valid: bool = Field(description="True only if all citations reference real retrieved evidence")
    citations_found: List[str] = Field(default_factory=list, description="All citation strings parsed from answer")
    valid_citations: List[str] = Field(default_factory=list, description="Citations verified against retrieved evidence")
    invalid_citations: List[str] = Field(default_factory=list, description="Fabricated or unretrieved citations")
    unsupported_claims: List[str] = Field(default_factory=list, description="Claims flagged as lacking textual overlap")
    details: str = Field(description="Human-readable explanation of the audit verdict")


class ProviderResponse(BaseModel):
    """Raw response generated by a model provider."""
    text: str = Field(description="Generated answer text")
    provider_name: str = Field(description="Identifier e.g., 'gemini' or 'offline_mock'")
    mode: str = Field(description="Execution mode e.g., 'gemini' or 'offline_extract'")
    is_refusal: bool = Field(default=False, description="True if provider refused due to insufficient evidence")
    raw_metadata: Dict[str, Any] = Field(default_factory=dict)


class TutorResponse(BaseModel):
    """Complete, audited instructional response presented to the user/UI."""
    query: str
    answer: str
    provider_name: str
    mode: str
    is_refusal: bool
    audit_passed: bool = Field(description="True if citation audit passed; False if failed or unverified")
    audit_result: AuditResult
    retrieved_evidence: List[EvidenceItem]
